const dictionaries: Record<Lang, Dict> = { en: { ...en, ...extraEn }, bn: { ...bn, ...extraBn } };

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
}

// Kept on globalThis so a hot reload of this module does not create a second context (which crashes open pages).
const I18nContext: React.Context<I18nContextValue | null> =
  ((globalThis as Record<string, unknown>).__localfixI18nCtx as React.Context<I18nContextValue | null>) ??
  ((globalThis as Record<string, unknown>).__localfixI18nCtx = createContext<I18nContextValue | null>(null));

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('en');

  const t = useCallback(
    (key: string) => dictionaries[lang][key] ?? key,
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

// Sync language preference to user's profile
export function useLangSync() {
  const { lang, setLang } = useI18n();
  const { session } = useAuth();

  useEffect(() => {
    if (session?.user) {
      supabase
        .from('profiles')
        .update({ preferred_language: lang })
        .eq('id', session.user.id)
        .then(({ error }) => {
          if (error) console.error('Failed to sync language:', error.message);
        });
    }
  }, [lang, session]);

  // Load preferred language from profile on mount
  useEffect(() => {
    if (session?.user) {
      supabase
        .from('profiles')
        .select('preferred_language')
        .eq('id', session.user.id)
        .maybeSingle()
        .then(({ data }) => {
          if (data?.preferred_language === 'en' || data?.preferred_language === 'bn') {
            setLang(data.preferred_language);
          }
        });
    }
  }, [session, setLang]);
}
